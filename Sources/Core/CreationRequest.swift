import Foundation

public enum RequestContext: String, Codable, Sendable {
    case container, items, sidebar
}

public struct CreationRequest: Codable, Equatable, Sendable {
    public let id: UUID
    public let createdAt: Date
    public let targetPath: String
    public let context: RequestContext

    public init(id: UUID = UUID(), createdAt: Date = Date(), targetPath: String, context: RequestContext) {
        self.id = id
        self.createdAt = createdAt
        self.targetPath = targetPath
        self.context = context
    }

    private enum CodingKeys: String, CodingKey, CaseIterable {
        case id, createdAt, targetPath, context
    }

    private struct AnyKey: CodingKey {
        let stringValue: String
        let intValue: Int? = nil
        init?(stringValue: String) { self.stringValue = stringValue }
        init?(intValue: Int) { return nil }
    }

    public init(from decoder: Decoder) throws {
        let allKeys = try decoder.container(keyedBy: AnyKey.self).allKeys
        guard Set(allKeys.map(\.stringValue)) == Set(CodingKeys.allCases.map(\.rawValue)) else {
            throw DecodingError.dataCorrupted(.init(codingPath: decoder.codingPath, debugDescription: "Unexpected request fields."))
        }
        let values = try decoder.container(keyedBy: CodingKeys.self)
        id = try values.decode(UUID.self, forKey: .id)
        createdAt = try values.decode(Date.self, forKey: .createdAt)
        targetPath = try values.decode(String.self, forKey: .targetPath)
        context = try values.decode(RequestContext.self, forKey: .context)
    }
}

public enum RequestLink {
    public static func url(for id: UUID) -> URL {
        // The value is a UUID generated by Foundation, never a path or other user input.
        URL(string: "rightclicktext://create/\(id.uuidString)")!
    }

    public static func requestID(from url: URL) -> UUID? {
        guard let parts = URLComponents(url: url, resolvingAgainstBaseURL: false),
              parts.scheme == "rightclicktext", parts.host == "create", parts.percentEncodedHost == "create",
              parts.user == nil, parts.password == nil, parts.port == nil,
              parts.query == nil, parts.fragment == nil else { return nil }
        let path = parts.percentEncodedPath
        guard path.hasPrefix("/"), path.utf8.count == 37 else { return nil }
        let token = String(path.dropFirst())
        guard let id = UUID(uuidString: token), id.uuidString.caseInsensitiveCompare(token) == .orderedSame else { return nil }
        return id
    }
}
